import { getMappingsForCrm, mapFieldValue } from "./crm-mappings";

interface ExportRow {
  originalData: Record<string, string>;
  enrichments: Record<
    string,
    {
      value: unknown;
      confidence: number;
      sourceContext?: Array<{ url: string }>;
      scrapedAt?: string;
    }
  >;
  status: string;
}

function escapeCsv(value: string): string {
  if (
    value.includes(",") ||
    value.includes('"') ||
    value.includes("\n") ||
    value.includes("\r")
  ) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

function formatValue(v: unknown): string {
  if (v === null || v === undefined) return "";
  if (Array.isArray(v)) return v.join(", ");
  return String(v);
}

function getSourceString(
  enrichment: {
    sourceContext?: Array<{ url: string }>;
  } | undefined
): string {
  if (!enrichment?.sourceContext?.length) return "";
  return enrichment.sourceContext.map((s) => s.url).join("; ");
}

export function exportCrmCsv(
  rows: ExportRow[],
  crm: "salesforce" | "hubspot",
  originalHeaders: string[],
  enrichmentFields: string[],
  includeMetadata = false
): string {
  const mappings = getMappingsForCrm(crm);
  const lines: string[] = [];

  // Comment line
  const crmLabel = crm === "salesforce" ? "Salesforce" : "HubSpot";
  lines.push(`# ${crmLabel} Import — Generated by Open Enrich`);

  // Build header row
  const headers: string[] = [...originalHeaders];
  for (const field of enrichmentFields) {
    const mapping = mappings[field];
    const crmField = mapping ? mapping.crmField : field;
    headers.push(crmField);
    if (includeMetadata) {
      headers.push(`${crmField}_confidence`);
      headers.push(`${crmField}_source`);
    }
  }
  lines.push(headers.map(escapeCsv).join(","));

  // Data rows
  for (const row of rows) {
    const cells: string[] = originalHeaders.map((h) =>
      escapeCsv(row.originalData[h] ?? "")
    );
    for (const field of enrichmentFields) {
      const enrichment = row.enrichments[field];
      if (!enrichment) {
        cells.push("");
        if (includeMetadata) {
          cells.push("");
          cells.push("");
        }
      } else {
        const mapped = mapFieldValue(field, enrichment.value, crm);
        cells.push(escapeCsv(mapped.value));
        if (includeMetadata) {
          cells.push(escapeCsv(String(enrichment.confidence)));
          cells.push(escapeCsv(getSourceString(enrichment)));
        }
      }
    }
    lines.push(cells.join(","));
  }

  return lines.join("\n");
}

export function exportRawCsv(
  rows: ExportRow[],
  originalHeaders: string[],
  enrichmentFields: string[],
  includeMetadata = false
): string {
  const lines: string[] = [];

  // Build header row
  const headers: string[] = [...originalHeaders];
  for (const field of enrichmentFields) {
    headers.push(field);
    if (includeMetadata) {
      headers.push(`${field}_confidence`);
      headers.push(`${field}_source`);
    }
  }
  lines.push(headers.map(escapeCsv).join(","));

  // Data rows
  for (const row of rows) {
    const cells: string[] = originalHeaders.map((h) =>
      escapeCsv(row.originalData[h] ?? "")
    );
    for (const field of enrichmentFields) {
      const enrichment = row.enrichments[field];
      if (!enrichment) {
        cells.push("");
        if (includeMetadata) {
          cells.push("");
          cells.push("");
        }
      } else {
        cells.push(escapeCsv(formatValue(enrichment.value)));
        if (includeMetadata) {
          cells.push(escapeCsv(String(enrichment.confidence)));
          cells.push(escapeCsv(getSourceString(enrichment)));
        }
      }
    }
    lines.push(cells.join(","));
  }

  return lines.join("\n");
}

export function exportJson(
  rows: ExportRow[],
  enrichmentFields: string[]
): string {
  const output = rows.map((row) => {
    const entry: Record<string, unknown> = { ...row.originalData };
    for (const field of enrichmentFields) {
      const enrichment = row.enrichments[field];
      if (enrichment) {
        entry[field] = {
          value: enrichment.value,
          confidence: enrichment.confidence,
          ...(enrichment.sourceContext?.length
            ? { sources: enrichment.sourceContext.map((s) => s.url) }
            : {}),
          ...(enrichment.scrapedAt ? { scrapedAt: enrichment.scrapedAt } : {}),
        };
      }
    }
    entry._status = row.status;
    return entry;
  });

  return JSON.stringify(output, null, 2);
}

export function exportTsv(
  rows: ExportRow[],
  originalHeaders: string[],
  enrichmentFields: string[]
): string {
  const lines: string[] = [];

  const headers = [...originalHeaders, ...enrichmentFields];
  lines.push(headers.join("\t"));

  for (const row of rows) {
    const cells: string[] = originalHeaders.map(
      (h) => (row.originalData[h] ?? "").replace(/\t/g, " ").replace(/\n/g, " ")
    );
    for (const field of enrichmentFields) {
      const enrichment = row.enrichments[field];
      if (!enrichment) {
        cells.push("");
      } else {
        cells.push(
          formatValue(enrichment.value).replace(/\t/g, " ").replace(/\n/g, " ")
        );
      }
    }
    lines.push(cells.join("\t"));
  }

  return lines.join("\n");
}

export function triggerDownload(
  content: string,
  filename: string,
  mimeType = "text/csv;charset=utf-8;"
): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.style.display = "none";
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export async function copyToClipboard(text: string): Promise<void> {
  await navigator.clipboard.writeText(text);
}
